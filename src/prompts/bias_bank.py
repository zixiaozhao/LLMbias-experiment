def _normalize_base(base: str) -> str:
    normalized = base.strip().lower().replace(" ", "_").replace("-", "_")
    normalized_aliases = {
        alias.lower().replace(" ", "_").replace("-", "_"): target
        for alias, target in ALIASES.items()
    }
    return normalized_aliases.get(normalized, normalized)


def normalize_bias_type(bias_type: str) -> str:
    """Return a canonical bias key and reject unknown or malformed values."""
    if not bias_type or not bias_type.strip():
        return "none"

    parts = bias_type.split(":")
    if len(parts) > 2:
        raise ValueError(f"Invalid bias_type {bias_type!r}: expected '<name>[:A|B]'.")

    base = _normalize_base(parts[0])
    if base == "none":
        if len(parts) == 2 and parts[1].strip():
            raise ValueError("bias_type 'none' does not accept an A/B side.")
        return "none"

    if len(parts) == 1 or not parts[1].strip():
        side = "A"
    else:
        side = parts[1].strip().upper()
        if side not in {"A", "B"}:
            raise ValueError(
                f"Invalid bias side {parts[1]!r} in {bias_type!r}: expected A or B."
            )

    key = f"{base}:{side}"
    if key not in BIAS_BANK:
        valid_bases = sorted(
            {item.split(":", 1)[0] for item in BIAS_BANK if item != "none"}
        )
        raise ValueError(
            f"Unknown bias_type {bias_type!r}. Valid names: none, "
            + ", ".join(valid_bases)
        )
    return key


def bias_side(bias_type: str) -> Optional[str]:
    key = normalize_bias_type(bias_type)
    return None if key == "none" else key.rsplit(":", 1)[1]


def bias_suffix_for_filename(bias_type: str) -> str:
    key = normalize_bias_type(bias_type)
    if key == "none":
        return ""
    return f"__bias={key.lower().replace(':', '_')}"


def get_bias_pair(bias_type: str) -> Dict[str, str]:
    key = normalize_bias_type(bias_type)
    return BIAS_BANK[key]
